#: Version marker of the key format. Bump only with a parser change.
KEY_PREFIX = "YRD1"

#: The Ed25519 public key your issued keys are verified against, base32
#: (RFC 4648, unpadded -- 52 characters for the 32-byte raw key). Replace it
#: with the value printed by ``python tools/make_license_key.py --gen-keypair
#: --embed`` when the master private key is rotated. Everything stops
#: verifying if this is left at the placeholder, which is the safe failure.
# >>> PUBLIC KEY (generated by tools/make_license_key.py; do not edit by hand)
PUBLIC_KEY = '34JBOIAPPC4ECYHZLAHW53QQTKS6XROP2HZPX3TTWRVHSGDP3IWQ'
# <<< PUBLIC KEY

_B32_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"
_B32_LEN = {b: i for i, b in enumerate(_B32_ALPHABET)}


# --------------------------------------------------------------------------- #
# Errors -- same user_message contract as the engine hierarchy, but licensing
# is not document processing, so the engine module stays untouched.
# --------------------------------------------------------------------------- #
class LicenseError(ValueError):
    """Base for license problems. Carries a message safe to show the user."""

    default_message = "The license could not be verified."

    def __init__(self, message: str | None = None, *, user_message: str | None = None) -> None:
        super().__init__(message or self.default_message)
        self.user_message = user_message or (message or self.default_message)


class InvalidLicenseError(LicenseError):
    """Malformed key, wrong signature, or a payload this build cannot read.

    The constructor message is a developer-facing detail ("Key is truncated
    or has mixed halves"); the user always sees one fixed sentence, so a
    guesser learns nothing about where their forged key failed.
    """

    default_message = "This license key is not valid."

    def __init__(self, message: str | None = None, *, user_message: str | None = None) -> None:
        super().__init__(
            message,
            user_message=user_message
            or (
                "This license key is not valid. Check for a mistyped "
                "character, or contact Pryonx for the correct key."
            ),
        )


class LicenseExpiredError(LicenseError):
    """The key verified, but its term has ended."""

    default_message = "This license has expired."

    def __init__(self, expires: dt.date) -> None:
        self.expires = expires
        super().__init__(
            f"License expired on {expires.isoformat()}.",
            user_message=(
                f"This license expired on {expires:%d %b %Y}. Contact Pryonx to "
                "renew it."
            ),
        )


class LicenseMachineError(LicenseError):
    """The key is genuine but bound to a different computer."""

    default_message = "This license is registered to a different computer."

    def __init__(self, bound_to: str, this_machine: str) -> None:
        self.bound_to = bound_to
        self.this_machine = this_machine
        super().__init__(
            f"License bound to {bound_to}, this machine is {this_machine}.",
            user_message=(
                "This license is registered to a different computer.\n"
                f"This machine's ID is {this_machine}.\n\n"
                "Ask Pryonx for a key bound to this machine, or for a reissue "
                "if your hardware changed."
            ),
        )


# --------------------------------------------------------------------------- #
# Key codec
# --------------------------------------------------------------------------- #
def _b32encode(raw: bytes) -> str:
    return base64.b32encode(raw).decode("ascii").rstrip("=")


def _b32decode(text: str) -> bytes:
    padding = (-len(text)) % 8
    return base64.b32decode(text + "=" * padding)


def render_key(payload_bytes: bytes, signature: bytes) -> str:
    """Serialise the parts into the human-friendly ``YRD1-AAAAA-...`` form."""

    blob = struct.pack(">H", len(payload_bytes)) + payload_bytes + signature
    stream = _b32encode(blob)
    groups = [stream[i : i + 5] for i in range(0, len(stream), 5)]
    return f"{KEY_PREFIX}-{'-'.join(groups)}"


def parse_key(text: str) -> tuple[bytes, bytes]:
    """Split a license key into ``(payload_bytes, signature_bytes)``.

    Tolerates arbitrary spaces, dashes, line breaks and case -- anything a
    mail client or a phone conversation can do to a key. Raises
    :class:`InvalidLicenseError` for anything that is not a well-formed
    ``YRD1`` stream of the right shape.
    """

    if not text or not text.strip():
        raise InvalidLicenseError("Empty license key.")
    # 'YRD1' cannot collide with the base32 stream because '1' is not in the
    # RFC 4648 alphabet -- stripping every occurrence of the prefix is safe
    # regardless of how the dashes and spaces were mangled in transit.
    squashed = re.sub(r"[^0-9A-Z]", "", text.strip().upper().replace(KEY_PREFIX, ""))
    try:
        blob = _b32decode(squashed)
    except (ValueError, base64.binascii.Error) as exc:
        raise InvalidLicenseError("Key contains characters outside the alphabet.") from exc
    if len(blob) < 2 + 64:
        raise InvalidLicenseError("Key is too short.")
    (payload_len,) = struct.unpack(">H", blob[:2])
    payload = blob[2 : 2 + payload_len]
    signature = blob[2 + payload_len :]
    if len(payload) != payload_len or len(signature) != 64:
        raise InvalidLicenseError("Key is truncated or has mixed halves.")
    try:
        decoded = json.loads(payload.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        raise InvalidLicenseError("Payload is not readable JSON.") from exc
    if not isinstance(decoded, dict) or not {"c", "e", "i", "x", "m"} <= set(decoded):
        raise InvalidLicenseError("Payload is missing required fields.")
    return payload, signature


def _public_key() -> Ed25519PublicKey:
    if PUBLIC_KEY.startswith("PLACEHOLDER"):
        raise InvalidLicenseError(
            "This build has no publisher key embedded.",
            user_message=(
                "This YourDoc build cannot verify license keys yet: the "
                "publisher public key has not been embedded. Run "
                "'python tools/make_license_key.py --gen-keypair --embed' to "
                "initialise the licence system, then rebuild."
            ),
        )
    return Ed25519PublicKey.from_public_bytes(_b32decode(PUBLIC_KEY))


# --------------------------------------------------------------------------- #
# Verification
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class LicenseInfo:
    """A verified license: who it was sold to, what it covers and when it ends."""

    holder: str
    edition: str
    issued: dt.date
    expires: dt.date
    machine_id: str

    @property
    def days_left(self) -> int:
        """Whole days until expiry (negative once past)."""

        return (self.expires - dt.date.today()).days

    @property
    def expiring_soon(self) -> bool:
        """Whether the licence is live but inside its final 30 days."""

        return 0 <= self.days_left <= 30


def verify_key(text: str, *, check_machine: bool = True) -> LicenseInfo:
    """Verify a license key and return its :class:`LicenseInfo`.

    Checks, in order: shape, signature (against :data:`PUBLIC_KEY`), required
    fields, expiry, and -- unless *check_machine* is False -- that the payload
    names *this* computer. ``check_machine=False`` exists for pre-install
    checks on the seller's side; the application always verifies binding.

    Raises a :class:`LicenseError` subclass with a ``user_message`` ready to
    show in the GUI.
    """

    payload, signature = parse_key(text)
    try:
        _public_key().verify(signature, payload)
    except InvalidSignature as exc:
        raise InvalidLicenseError("Signature does not match the payload.") from exc

    data = json.loads(payload.decode("utf-8"))
    try:
        issued = dt.date.fromtimestamp(data["i"])
        expires = dt.date.fromtimestamp(data["x"])
    except (OSError, ValueError, OverflowError) as exc:
        raise InvalidLicenseError("Payload timestamps are unreadable.") from exc

    machine = str(data["m"])
    if not str(data["c"]).strip() or not str(data["e"]).strip():
        raise InvalidLicenseError("Payload is missing holder or edition.")

    today = dt.date.today()
    if today > expires:
        raise LicenseExpiredError(expires)
    if check_machine and machine != machine_id():
        raise LicenseMachineError(bound_to=machine, this_machine=machine_id())
    return LicenseInfo(
        holder=str(data["c"]),
        edition=str(data["e"]),
        issued=issued,
        expires=expires,
        machine_id=machine,
    )


# --------------------------------------------------------------------------- #
# Machine fingerprint
# --------------------------------------------------------------------------- #
_MAC_CHARS = re.compile(r"[0-9A-F]{12}")


def _normalize_mac(raw: str) -> str | None:
    """Return a 12-hex MAC, or ``None`` if it is not globally unique/valid."""

    hexed = re.sub(r"[^0-9A-F]", "", raw.upper())
    if len(hexed) != 12 or _MAC_CHARS.fullmatch(hexed) is None:
        return None
    if hexed in ("000000000000", "FFFFFFFFFFFF"):
        return None
    # Bit 1 of the first octet: locally administered (virtual, Bluetooth,
    # Windows randomised addresses). Those churn too often to bind a licence.
    if int(hexed[:2], 16) & 0x02:
        return None
    return hexed


def _parse_getmac_csv(stdout: str) -> set[str]:
    """Extract globally-unique MACs from ``getmac /fo csv /nh`` output."""

    found: set[str] = set()
    for line in (stdout or "").splitlines():
        first = line.split('","')[0].strip('",; ')
        mac = _normalize_mac(first)
        if mac:
            found.add(mac)
    return found


# Linux: interface directories under /sys/class/net. ``has_device`` is True
# when the interface is backed by a real hardware device (a ``device`` symlink);
# loopback, bridges, veth, docker0 and tun/tap have none, so they are skipped.
SysNetEntry = tuple[str, bool, str]  # (name, has_device, address)


def _parse_sys_class_net(entries: list[SysNetEntry]) -> set[str]:
    """Pure: keep only hardware-backed interfaces with a stable unicast MAC."""

    found: set[str] = set()
    for _name, has_device, address in entries:
        if not has_device:
            continue
        mac = _normalize_mac(address)
        if mac:
            found.add(mac)
    return found


def _parse_networksetup(stdout: str) -> set[str]:
    """Extract hardware-port MACs from macOS ``networksetup -listallhardwareports``."""

    found: set[str] = set()
    for line in (stdout or "").splitlines():
        line = line.strip()
        if line.lower().startswith("ethernet address"):
            mac = _normalize_mac(line.split(":", 1)[1])
            if mac:
                found.add(mac)
    return found


def _windows_macs() -> set[str]:
    try:
        outcome = subprocess.run(
            ["getmac", "/fo", "csv", "/nh"],
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return set()
    return _parse_getmac_csv(outcome.stdout)


def _linux_macs() -> set[str]:
    entries: list[SysNetEntry] = []
    try:
        base = pathlib.Path("/sys/class/net")
        for iface in sorted(p for p in base.glob("*") if p.is_dir()):
            try:
                address = (iface / "address").read_text().strip()
            except OSError:
                address = ""
            entries.append((iface.name, (iface / "device").exists(), address))
    except OSError:
        return set()
    return _parse_sys_class_net(entries)


def _macos_macs() -> set[str]:
    try:
        outcome = subprocess.run(
            ["networksetup", "-listallhardwareports"],
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return set()
    return _parse_networksetup(outcome.stdout)


def _collect_macs() -> list[str]:
    """Globally unique MAC addresses of this machine's *hardware* adapters.

    Only physically-backed, connected adapters count: loopback, bridges and
    virtual/tun interfaces -- and locally-administered addresses (Bluetooth,
    virtual NICs, OS MAC randomisation, handled inside :func:`_normalize_mac`)
    -- churn too often to bind a paid licence to. ``uuid.getnode()`` is folded
    in as a cross-check on every platform.
    """

    platform = sys.platform
    if platform.startswith("win"):
        found = _windows_macs()
    elif platform == "linux":
        found = _linux_macs()
    elif platform == "darwin":
        found = _macos_macs()
    else:
        found = set()
    node = f"{uuid.getnode():012x}"
    mac = _normalize_mac(node)
    if mac:
        found.add(mac)
    return sorted(found)


def _parse_ioreg_uuid(stdout: str) -> str | None:
    """Pure: pull ``IOPlatformUUID`` out of ``ioreg`` device-tree output."""

    match = re.search(r'"IOPlatformUUID"\s*=\s*"([^"]+)"', stdout or "")
    return match.group(1) if match else None


def _windows_machine_guid() -> str | None:
    """The Windows crypto MachineGuid -- stable for the life of the OS install."""

    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_LOCAL_MACHINE,
            r"SOFTWARE\Microsoft\Cryptography",
            0,
            winreg.KEY_READ | winreg.KEY_WOW64_64KEY,
        ) as handle:
            value, _ = winreg.QueryValueEx(handle, "MachineGuid")
        return str(value)
    except OSError:
        return None


def _machine_guid() -> str | None:
    """The OS-stable identifier used when no adapter MAC qualifies.

    Windows -> registry ``MachineGuid``; Linux -> ``/etc/machine-id``; macOS ->
    ``IOPlatformUUID``. Each is fixed for the life of that OS install, so a
    NIC-less or all-virtual machine still yields a stable ID (the EULA says such
    installs bind to the OS rather than the network adapter).
    """

    platform = sys.platform
    if platform.startswith("win"):
        return _windows_machine_guid()
    if platform == "linux":
        for path in ("/etc/machine-id", "/var/lib/dbus/machine-id"):
            try:
                value = pathlib.Path(path).read_text().strip()
            except OSError:
                continue
            if value:
                return value
        return None
    if platform == "darwin":
        try:
            outcome = subprocess.run(
                ["ioreg", "-rd1", "-c", "IOPlatformExpertDevice"],
                capture_output=True,
                text=True,
                timeout=10,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            return None
        return _parse_ioreg_uuid(outcome.stdout)
    return None


def _group(body: str, size: int = 5) -> str:
    return "-".join(body[i : i + size] for i in range(0, len(body), size))


def _fingerprint_source() -> list[str]:
    """What the machine ID hashes over: adapter MACs, or the OS GUID alone."""

    macs = _collect_macs()
    if macs:
        return macs
    guid = _machine_guid()
    return ["G|" + guid] if guid else []


def machine_id() -> str:
    """This computer's licence-binding ID, e.g. ``YRD-M1-AB12C-D34EF``.

    Cached per process: adapters do not change while the app runs, and the
    ``getmac`` call should not repeat on every verification pass.
    """

    global _machine_id_cache
    if _machine_id_cache is None:
        source = _fingerprint_source()
        if not source:
            raise LicenseError(
                "No stable hardware identifier found.",
                user_message=(
                    "YourDoc could not read a stable machine identifier. Check "
                    "that a network adapter is connected, then try again."
                ),
            )
        digest = hashlib.sha256("|".join(source).encode("utf-8")).hexdigest()[:10]
        _machine_id_cache = f"YRD-M1-{_group(digest.upper())}"
    return _machine_id_cache


#: Result of :func:`machine_id`, computed once per process.
_machine_id_cache: str | None = None


def _reset_machine_id_cache() -> None:
    """Drop the cache (test hook: monkeypatching the collectors between cases)."""

    global _machine_id_cache
    _machine_id_cache = None


def machine_id_or_none() -> str | None:
    """Best-effort :func:`machine_id` for dialogs that must not crash."""

    try:
        return machine_id()
    except LicenseError:
        return None


