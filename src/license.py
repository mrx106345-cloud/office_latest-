"""Offline commercial licensing for **YourDoc**, a **Pryonx** product.

YourDoc is sold per machine. A *license key* is a small payload (holder,
edition, expiry, machine fingerprint) signed by Pryonx with an **Ed25519 key**;
this module verifies it with the embedded public key. Everything is local --
there is no activation server, no network call and no telemetry. The
:mod:`cryptography` package is already a runtime dependency (pypdf uses it for
AES), so licensing adds nothing new to the bundle.

Key anatomy
-----------
``YRD1-AAAAA-BBBBB-...`` -- one base32 stream holding::

    [2 bytes payload length][payload JSON][64-byte Ed25519 signature]

Base32 (RFC 4648 alphabet, unpadded) because a human has to retype or paste it
over the phone without corrupting it. Parsing tolerates any spacing, dashes,
line breaks and case: the customer's copy of the key is the *shape you printed*
in the email, not a byte-exact string.

Payload fields: ``c`` holder, ``e`` edition, ``i`` issued (unix), ``x`` expires
(unix), ``m`` machine ID. The expiry lives **inside the signed payload**, so
one build of the application serves every customer and every term; issuing a
key never requires rebuilding the product.

Machine binding
---------------
:func:`machine_id` fingerprints the *globally unique* MAC addresses of the
network adapters (locally-administered ones -- Bluetooth, virtual NICs, Windows
randomised addresses -- are excluded so normal laptop dock/undock and MAC
randomisation do not break a paid licence). With no qualifying adapter it
falls back to an OS-stable identifier (Windows ``MachineGuid``, Linux
``/etc/machine-id``, macOS ``IOPlatformUUID``), which is fixed for the life of
the OS install. If the fingerprint changes the licence stops verifying and the
customer is asked to request a reissue -- by design, see the EULA.

This is a deterrent, not hardware DRM: it stops "one buyer, many friends",
which is the commercial goal, and a determined attacker with admin rights can
spoof a MAC. There is no offline scheme that can do better.
"""

