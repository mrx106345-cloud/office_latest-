def load_private_key(path) -> Ed25519PrivateKey:
    """Read an unencrypted PEM Ed25519 private key written by the keygen tool."""

    from pathlib import Path

    from cryptography.hazmat.primitives import serialization

    pem = Path(path).read_bytes()
    key = serialization.load_pem_private_key(pem, password=None)
    if not isinstance(key, Ed25519PrivateKey):
        raise ValueError("The key file is not an Ed25519 private key.")
    return key


def public_key_b32(private: Ed25519PrivateKey) -> str:
    """The base32 constant to embed as :data:`PUBLIC_KEY`."""

    from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

    raw = private.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    return _b32encode(raw)


def issue_key(
    private: Ed25519PrivateKey,
    *,
    holder: str,
    edition: str,
    expires: dt.datetime,
    machine: str,
    issued: dt.datetime | None = None,
) -> str:
    """Sign a payload and render the customer-ready key."""

    issued = issued or dt.datetime.now()
    payload = json.dumps(
        {
            "c": holder.strip(),
            "e": edition.strip(),
            "i": int(issued.timestamp()),
            "x": int(expires.timestamp()),
            "m": machine.strip().upper(),
        },
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")
    return render_key(payload, private.sign(payload))
