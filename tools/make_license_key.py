"""Issue YourDoc license keys (Pryonx internal tool -- never shipped).

This is the seller's side of :mod:`src.license`. You run it each time a
customer pays; it prints a key to paste into the reply email. The application
itself is **never rebuilt per customer** -- the term and machine binding live
inside the signed key, not in the binary.

One-time setup
--------------
::

    python tools/make_license_key.py --gen-keypair --embed

Writes the master private key to ``%LOCALAPPDATA%\\Pryonx\\pryonx-license.key``
(deliberately *outside* this project, and ``.gitignore`` blocks ``*.key`` /
``*.pem`` wherever it lands), then embeds the matching public key into
``src/license.py`` between the marked lines. **Back the private key up offline
now**: losing it means no further keys can ever be issued for this product.

Issuing a key
-------------
::

    # The customer sends the ID shown by their activation dialog:
    python tools/make_license_key.py --holder "Acme Ltd" --edition standard \
        --machine YRD-M1-AB12C-D34EF

Default term is five years; override per deal with ``--years``, ``--months``,
``--days`` or an exact ``--expires 2029-06-30``. ``--renew "<old key>"``
reissues for the same holder and machine without retyping the ID.
"""

from __future__ import annotations

import argparse
import calendar
import datetime as dt
import os
import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src import license as licensing  # noqa: E402

DEFAULT_YEARS = 5
#: Where the master private key lives by default -- outside every checkout.
DEFAULT_KEY_DIR = Path(
    os.environ.get("LOCALAPPDATA", str(Path.home()))
) / "Pryonx"
KEY_FILENAME = "pryonx-license.key"

#: The embedding target: src/license.py delimits the constant with these.
EMBED_START = "# >>> PUBLIC KEY (generated by tools/make_license_key.py; do not edit by hand)"
EMBED_END = "# <<< PUBLIC KEY"


# --------------------------------------------------------------------------- #
# Term arithmetic (calendar-accurate, no dateutil dependency)
# --------------------------------------------------------------------------- #
def _add_days(base: dt.date, *, years: int = 0, months: int = 0, days: int = 0) -> dt.date:
    total_months = years * 12 + months
    # Work in 0-indexed months, then convert the year back and the month
    # forward. ``base.year * 12 + (base.month - 1)`` is the absolute month
    # index; the quotient after divmod *is* the year (no +1) and the
    # remainder is the 0-indexed month (so it needs +1).
    year, month = divmod(base.year * 12 + (base.month - 1) + total_months, 12)
    month += 1
    day = min(base.day, calendar.monthrange(year, month)[1])
    return dt.date(year, month, day) + dt.timedelta(days=days)


def compute_expiry(
    today: dt.date,
    *,
    years: int,
    months: int,
    days: int,
    expires: str | None,
) -> dt.date:
    """Resolve the four term flags into one end date.

    ``--expires`` wins outright (an invoice may name a calendar date); the
    others accumulate. With none of them given the caller supplies the default
    five-year term *before* calling.
    """

    if expires:
        try:
            return dt.date.fromisoformat(expires)
        except ValueError as exc:
            raise SystemExit(f"--expires wants YYYY-MM-DD, got {expires!r}") from exc
    if years or months or days:
        return _add_days(today, years=years, months=months, days=days)
    return _add_days(today, years=DEFAULT_YEARS)


# --------------------------------------------------------------------------- #
# --gen-keypair
# --------------------------------------------------------------------------- #
def generate_keypair(out_path: Path, *, embed: bool) -> int:
    from cryptography.hazmat.primitives import serialization

    if out_path.exists():
        print(f"A private key already exists at:\n  {out_path}\n"
              "Reuse it (keys issued before stay valid), or move it aside "
              "deliberately before generating a new one.", file=sys.stderr)
        return 1
    out_path.parent.mkdir(parents=True, exist_ok=True)
    private = licensing.Ed25519PrivateKey.generate()
    pem = private.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    out_path.write_bytes(pem)
    try:
        out_path.chmod(0o600)  # best effort on Windows; ACL is the user's job
    except OSError:
        pass
    print(f"Private key written to:  {out_path}\nBACK IT UP NOW - losing it "
          "means no future keys can be issued.")

    public_b32 = licensing.public_key_b32(private)
    if embed:
        target = PROJECT_ROOT / "src" / "license.py"
        text = target.read_text(encoding="utf-8")
        marker = re.compile(
            re.escape(EMBED_START) + r".*?" + re.escape(EMBED_END), re.DOTALL
        )
        replacement = (
            f"{EMBED_START}\nPUBLIC_KEY = {public_b32!r}\n{EMBED_END}"
        )
        if marker.search(text):
            text = marker.sub(lambda _m: replacement, text)
        else:
            # First run: replace the plain placeholder assignment and add the
            # markers so future rotations find the region.
            old = f'PUBLIC_KEY = "{licensing.PUBLIC_KEY}"'
            if old not in text and "PUBLIC_KEY = " not in text:
                raise SystemExit("Cannot locate the PUBLIC_KEY constant to embed.")
            text = re.sub(
                r'^PUBLIC_KEY = "[^"]*"',
                lambda _m: replacement,
                text,
                count=1,
                flags=re.MULTILINE,
            )
        target.write_text(text, encoding="utf-8")
        print(f"Public key embedded into {target}\n"
              "Rebuild the application so shipped builds carry it.")
    else:
        print(f"Public key (embed manually as PUBLIC_KEY in src/license.py):\n{public_b32}")
    return 0


# --------------------------------------------------------------------------- #
# Issuing
# --------------------------------------------------------------------------- #
def read_machine_id_interactively() -> int:
    """Print the *selling machine's* own ID (support runs it on a call)."""

    print(licensing.machine_id())
    return 0


def do_issue(args: argparse.Namespace) -> int:
    key_path = Path(args.key) if args.key else DEFAULT_KEY_DIR / KEY_FILENAME
    if not key_path.is_file():
        print(f"Private key not found: {key_path}\n"
              "Run:  python tools/make_license_key.py --gen-keypair --embed",
              file=sys.stderr)
        return 1
    private = licensing.load_private_key(key_path)

    holder = args.holder
    machine = args.machine
    edition = args.edition

    if args.renew:
        # Reissue inherits holder/machine from the old key after verifying it,
        # so a typo cannot silently renew someone else's licence onto a new ID.
        try:
            old = licensing.verify_key(args.renew, check_machine=False)
        except licensing.LicenseError as exc:
            print(f"Cannot renew: {exc.user_message}", file=sys.stderr)
            return 1
        holder = holder or old.holder
        machine = machine or old.machine_id
        edition = args.edition or old.edition

    if not holder:
        print("--holder is required (name the customer exactly as on the invoice).",
              file=sys.stderr)
        return 2
    if not machine:
        print("--machine is required: no unbound keys are issued. The buyer "
              "reads it out with the activation dialog or "
              "'YourDoc.exe --show-machine-id'.", file=sys.stderr)
        return 2
    if not machine.startswith("YRD-M1-"):
        print(f"--machine should look like YRD-M1-XXXXX-XXXXX, got {machine!r}",
              file=sys.stderr)
        return 2

    today = dt.date.today()
    explicit = any((args.years, args.months, args.days, args.expires))
    end = compute_expiry(
        today,
        years=args.years,
        months=args.months,
        days=args.days,
        expires=args.expires,
    ) if explicit else _add_days(today, years=DEFAULT_YEARS)
    if end <= today:
        print("The term ends in the past - the key would expire immediately.",
              file=sys.stderr)
        return 2
    # Expires at 23:59 local on the end date: the last day is fully usable.
    expiry_moment = dt.datetime(end.year, end.month, end.day, 23, 59, 59)

    key = licensing.issue_key(
        private,
        holder=holder,
        edition=edition,
        expires=expiry_moment,
        machine=machine,
    )
    term = (
        "exact date" if args.expires
        else f"{args.years or 0}y {args.months or 0}m {args.days or 0}d".strip()
        if explicit else "5 years (default)"
    )
    print()
    print(key)
    print()
    print(f"{holder} · {edition} · expires {end:%d %b %Y} ({term}) · "
          f"bound to {machine}")
    return 0


# --------------------------------------------------------------------------- #
def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Issue YourDoc license keys (Pryonx internal)."
    )
    parser.add_argument("--gen-keypair", action="store_true",
                        help="create the master private key (one time)")
    parser.add_argument("--out", default=None,
                        help=f"private key path (default {DEFAULT_KEY_DIR / KEY_FILENAME})")
    parser.add_argument("--embed", action="store_true",
                        help="with --gen-keypair: write the public key into src/license.py")
    parser.add_argument("--show-machine-id", action="store_true",
                        help="print this machine's ID and exit")
    parser.add_argument("--holder", help="customer name on the invoice")
    parser.add_argument("--edition", default="standard",
                        help="edition label carried in the key (default: standard)")
    parser.add_argument("--machine", help="buyer's machine ID (YRD-M1-...)")
    parser.add_argument("--years", type=int, default=0, help="term in years")
    parser.add_argument("--months", type=int, default=0, help="term in months")
    parser.add_argument("--days", type=int, default=0, help="term in days")
    parser.add_argument("--expires", help="exact end date, YYYY-MM-DD")
    parser.add_argument("--renew", metavar="OLDKEY",
                        help="reissue from a previous key (holder/machine inherited)")
    parser.add_argument("--key", default=None, help="private key file to sign with")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.gen_keypair:
        out = Path(args.out) if args.out else DEFAULT_KEY_DIR / KEY_FILENAME
        return generate_keypair(out, embed=args.embed)
    if args.show_machine_id:
        return read_machine_id_interactively()
    if any((args.holder, args.machine, args.renew, args.years, args.months,
            args.days, args.expires)):
        return do_issue(args)
    build_parser().print_help()
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
